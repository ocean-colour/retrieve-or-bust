#!/usr/bin/env python
"""
Build and cache the L23 depth-profile product, and report its coverage (M7 task 1).

Reads the three elastic ``Hydrolight1YY_profile.nc`` files through
:func:`robust.rt.data.l23.build_profile_product` -- µ at the deepest usable depth
per zenith, the asymptotic flag, µd(0⁻), KLu(0⁻) -- caches it next to the data
(:func:`~robust.rt.data.l23.default_profile_product_path`; ~13 MB, not committed),
and writes to ``design/ztt_l23/``:

- ``profile_product.md`` -- flag fractions overall, per wavelength and per
  zenith-spread band, with the µd / Gershun numbers the task gates on;
- ``fig_profile_coverage.png`` -- where in (log bb/a, log η_bb) the profiles
  measure µ∞ and where they do not.

Deterministic: a rerun rewrites identical arrays (the test suite checks the
builder bit for bit).

    python design/py/build_l23_profile_product.py            # build, cache, report
    python design/py/build_l23_profile_product.py --dry-run  # report only, no writes
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(Path(__file__).resolve().parent))

from run_validation import (  # noqa: E402
    INK_MUTED,
    apply_house_style,
    save_figure_atomically,
)

from robust.rt.data import l23 as L  # noqa: E402

OUT = ROOT / "design" / "ztt_l23"


def surface_iops():
    """bb/a and η_bb per (scene, λ) from the elastic surface file (zenith 0)."""
    batch = L.load_batch(zeniths=(0,), validate=False)
    bb = np.asarray(batch.iops.bb_w + batch.iops.bb_p, dtype=float)
    return bb / np.asarray(batch.iops.a, dtype=float), np.asarray(
        batch.iops.bb_w, dtype=float
    ) / bb


def report(product, x, eta) -> str:
    """The markdown summary."""
    frac = product.flag_fractions()
    ok = product.flag == L.FLAG_ASYMPTOTIC
    lines = [
        "# L23 depth-profile product — coverage",
        "",
        "*Generated by `design/py/build_l23_profile_product.py` (M7 task 1). "
        "Do not edit by hand.*",
        "",
        f"Product version {L.PROFILE_PRODUCT_VERSION}; asymptotic = the three "
        f"zeniths' µ at the deepest usable depth agree to < "
        f"{L.ASYMPTOTIC_SPREAD:.0%}; usable = Ed, Eu, Eo > {L.PROFILE_E_MIN:g}; "
        f"unusable = deepest usable depth < {L.PROFILE_MIN_DEPTH:g} m.",
        "",
        "| flag | fraction of 3320 × 81 (scene, λ) |",
        "|---|---|",
        *[f"| {name} | {value:.4f} |" for name, value in frac.items()],
        "",
        "| quantity | 1% | 16% | 50% | 84% | 99% |",
        "|---|---|---|---|---|---|",
    ]

    def row(label, values):
        q = np.nanpercentile(values, [1, 16, 50, 84, 99])
        return f"| {label} | " + " | ".join(f"{v:.4g}" for v in q) + " |"

    lines += [
        row("deepest usable depth (m)", product.z_deep),
        row("zenith spread of µ at depth", product.spread),
        row("bb/a, asymptotic points", x[ok]),
        row("bb/a, all points", x),
        row("η_bb, asymptotic points", eta[ok]),
        row("η_bb, all points", eta),
    ]
    for k, zen in enumerate(product.zeniths):
        lines.append(row(f"µd(0⁻), {zen}°", product.mu_d0[k]))
    lines += ["", "Asymptotic fraction by wavelength:", ""]
    lines += [
        "| λ (nm) | " + " | ".join(str(int(w)) for w in product.wave[::10]) + " |"
    ]
    lines += ["|---" * (len(product.wave[::10]) + 1) + "|"]
    lines += [
        "| asymptotic | " + " | ".join(f"{v:.3f}" for v in ok.mean(0)[::10]) + " |",
        "",
    ]
    return "\n".join(lines)


def figure(product, x, eta, path: Path) -> None:
    """Point density and asymptotic fraction in (log bb/a, log η_bb)."""
    plt = apply_house_style()
    lx, le = np.log10(x).ravel(), np.log10(eta).ravel()
    ok = (product.flag == L.FLAG_ASYMPTOTIC).ravel()
    bins = [np.linspace(-4.0, 0.0, 41), np.linspace(-1.8, 0.0, 37)]
    n_all, xe, ye = np.histogram2d(lx, le, bins=bins)
    n_ok, _, _ = np.histogram2d(lx[ok], le[ok], bins=bins)
    with np.errstate(invalid="ignore"):
        fraction = np.where(n_all >= 5, n_ok / n_all, np.nan)

    fig, axes = plt.subplots(1, 2, figsize=(10.5, 4.2), sharey=True)
    for ax in axes:
        ax.grid(False)
        ax.set_xlabel("log10(bb / a)")
    density = np.where(n_all > 0, n_all, np.nan)
    im0 = axes[0].pcolormesh(
        xe, ye, np.log10(density).T, cmap="Greys", vmin=0, shading="flat"
    )
    axes[0].set_title("L23 (scene, λ) points", loc="left", fontsize=10.5)
    axes[0].set_ylabel("log10(η_bb)")
    fig.colorbar(im0, ax=axes[0], label="log10(count per bin)")

    im1 = axes[1].pcolormesh(
        xe, ye, fraction.T, cmap="Blues", vmin=0, vmax=1, shading="flat"
    )
    axes[1].set_title(
        "profiles reach µ∞ (3 suns agree < 1% at depth)",
        loc="left",
        fontsize=10.5,
    )
    fig.colorbar(im1, ax=axes[1], label="asymptotic fraction (bins with ≥ 5 points)")
    for ax in axes:
        # TT's fitted range for Eq. (8), for orientation.
        ax.axvline(-1.0, color=INK_MUTED, lw=1, ls="--")
        ax.text(
            -1.05, -1.75, "TT fit: bb/a ≤ 0.1", color=INK_MUTED, fontsize=9, ha="right"
        )
    fig.tight_layout()
    save_figure_atomically(fig, path)
    plt.close(fig)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--dry-run", action="store_true", help="report, write nothing")
    args = parser.parse_args(argv)

    product = L.build_profile_product()
    x, eta = surface_iops()
    text = report(product, x, eta)
    print(text)
    if args.dry_run:
        return 0

    cache = L.default_profile_product_path()
    L.save_profile_product(product, cache)
    print(f"cached: {cache}")
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "profile_product.md").write_text(text)
    figure(product, x, eta, OUT / "fig_profile_coverage.png")
    print(f"wrote {OUT / 'profile_product.md'} and fig_profile_coverage.png")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
